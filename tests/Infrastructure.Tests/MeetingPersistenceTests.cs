    [Fact]
    public async Task The_list_query_translates_to_sql_and_orders_the_way_it_promises()
    {
        CancellationToken cancellationToken = TestContext.Current.CancellationToken;
        await using ServiceProvider services = await MigratedHostAsync(nameof(The_list_query_translates_to_sql_and_orders_the_way_it_promises), cancellationToken);

        await SaveAsync(services, Meeting.Create("Older day", new DateOnly(2026, 9, 16), null, Guid.CreateVersion7(), Created), cancellationToken);
        await SaveAsync(services, Meeting.Create("Earlier", Held, null, Guid.CreateVersion7(), Created.AddHours(-2)), cancellationToken);
        await SaveAsync(services, Meeting.Create("Later", Held, ["Dana Whitfield"], Guid.CreateVersion7(), Created), cancellationToken);

        await using AsyncServiceScope scope = services.CreateAsyncScope();

        // The Application-ring fake is LINQ to Objects, so the ordering and the projection are
        // only proven to be a *query* there. This is what proves the provider can translate them.
        PagedResult<MeetingSummaryDto> page = await QueriesIn(scope).ListAsync(null, null, cancellationToken);

        Assert.Equal(["Later", "Earlier", "Older day"], page.Items.Select(meeting => meeting.Title));
        Assert.Equal(3, page.Total);
        Assert.All(page.Items, meeting =>
        {
            Assert.Equal(0, meeting.RunCount);
            Assert.Equal(0, meeting.TrackedActionCount);
        });
    }

    [Fact]
    public async Task The_detail_query_translates_to_sql_and_carries_the_notes_and_the_attendees()
    {
        CancellationToken cancellationToken = TestContext.Current.CancellationToken;
        await using ServiceProvider services = await MigratedHostAsync(nameof(The_detail_query_translates_to_sql_and_carries_the_notes_and_the_attendees), cancellationToken);

        Meeting withNotes = NewMeeting("Weekly sync");
        MeetingNotes notes = withNotes.AttachNotes("  Dana will send the draft.\r\n", Created);
        await SaveAsync(services, withNotes, cancellationToken);

        Meeting withoutNotes = Meeting.Create("Solo review", Held, null, Guid.CreateVersion7(), Created);
        await SaveAsync(services, withoutNotes, cancellationToken);

        await using AsyncServiceScope scope = services.CreateAsyncScope();
        MeetingsQueries queries = QueriesIn(scope);

        MeetingDetailDto detail = await queries.GetAsync(withNotes.Id, cancellationToken);

        Assert.Equal(["Dana Whitfield"], detail.Attendees);
        Assert.Equal(withNotes.CreatedByUserId, detail.CreatedByUserId);
        Assert.NotNull(detail.Notes);
        Assert.Equal(notes.Id, detail.Notes.Id);
        Assert.Equal("  Dana will send the draft.\r\n", detail.Notes.Text);
        Assert.Equal(notes.Sha256, detail.Notes.Sha256);

        // A Meeting with no notes projects a null rather than an empty object or a missing row.
        MeetingDetailDto bare = await queries.GetAsync(withoutNotes.Id, cancellationToken);

        Assert.Null(bare.Notes);
        Assert.Empty(bare.Attendees);
    }


    [Fact]
    public async Task The_concurrency_token_is_the_system_column_not_one_the_migration_added()
    {
        CancellationToken cancellationToken = TestContext.Current.CancellationToken;
        string connectionString = await postgres.CreateDatabaseAsync(nameof(The_concurrency_token_is_the_system_column_not_one_the_migration_added), cancellationToken);

        await using ServiceProvider services = TestHost.Build(connectionString, TestHost.SeedingOff);
        await TestHost.MigrateAsync(services, cancellationToken);

        await using AsyncServiceScope scope = services.CreateAsyncScope();

        // The absence check below is satisfied just as happily by a Meeting that has no token at
        // all, so it cannot stand alone: delete the two lines in MeetingConfiguration that set
        // this and nothing would notice. This is the half that says the token exists.
        IProperty? token = scope.ServiceProvider.GetRequiredService<AppDbContext>()
            .Model
            .FindEntityType(typeof(Meeting))!
            .FindProperty(MeetingConfiguration.ConcurrencyTokenProperty);

        Assert.NotNull(token);
        Assert.True(token.IsConcurrencyToken);

        // Generated by the database on every write, which is what makes it a row version rather
        // than a value the model would have to maintain.
        Assert.Equal(ValueGenerated.OnAddOrUpdate, token.ValueGenerated);
        Assert.Equal(MeetingConfiguration.ConcurrencyTokenProperty, token.GetColumnName());

        Dictionary<string, string> columns = await ColumnsAsync(connectionString, "meetings", cancellationToken);

        // AD-20 puts `xmin` on Meeting. PostgreSQL already has a system column by that name, so a
        // real column would have failed the CREATE TABLE outright — this is what proves the token
        // is bound to the system column rather than shadowing it.
        Assert.DoesNotContain(MeetingConfiguration.ConcurrencyTokenProperty, columns.Keys);
    }


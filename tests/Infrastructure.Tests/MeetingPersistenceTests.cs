    /// <summary>
    /// The query class over the real read seam. It is registered by the Application ring's own
    /// <c>AddActionLedgerApplication</c>, which this host deliberately does not call — what is
    /// under test is the translation, not the registration.
    /// </summary>
    private static MeetingsQueries QueriesIn(AsyncServiceScope scope) =>
        new(scope.ServiceProvider.GetRequiredService<IReadDb>());

    private static Meeting NewMeeting(string title) =>
        Meeting.Create(title, Held, ["Dana Whitfield"], Guid.CreateVersion7(), Created);

    private static async Task SaveAsync(IServiceProvider services, Meeting meeting, CancellationToken cancellationToken)
    {
        await using AsyncServiceScope scope = services.CreateAsyncScope();

        scope.ServiceProvider.GetRequiredService<IMeetingRepository>().Add(meeting);
        await scope.ServiceProvider.GetRequiredService<IUnitOfWork>().CommitAsync(cancellationToken);
    }

    private static async Task<Meeting> ReadAsync(IServiceProvider services, Guid id, CancellationToken cancellationToken)
    {
        await using AsyncServiceScope scope = services.CreateAsyncScope();

        return await LoadAsync(scope, id, cancellationToken);
    }

    private static async Task<Meeting> LoadAsync(AsyncServiceScope scope, Guid id, CancellationToken cancellationToken)
    {
        Meeting? meeting = await scope.ServiceProvider.GetRequiredService<IMeetingRepository>()
            .FindByIdAsync(id, cancellationToken);

        Assert.NotNull(meeting);

        return meeting;
    }

    private async Task<string> MigratedDatabaseAsync(string name, CancellationToken cancellationToken)
    {
        string connectionString = await postgres.CreateDatabaseAsync(name, cancellationToken);

        await using ServiceProvider services = TestHost.Build(connectionString, TestHost.SeedingOff);
        await TestHost.MigrateAsync(services, cancellationToken);

        return connectionString;
    }

    private async Task<ServiceProvider> MigratedHostAsync(
        string name,
        CancellationToken cancellationToken,
        Action<IServiceCollection>? configure = null)
    {
        string connectionString = await postgres.CreateDatabaseAsync(name, cancellationToken);

        ServiceProvider services = TestHost.Build(connectionString, TestHost.SeedingOff, configure);

        await TestHost.MigrateAsync(services, cancellationToken);

        return services;
    }

    private static async Task<Dictionary<string, string>> ColumnsAsync(
        string connectionString,
        string table,
        CancellationToken cancellationToken)
    {
        Dictionary<string, string> columns = new(StringComparer.Ordinal);

        await using NpgsqlConnection connection = new(connectionString);
        await connection.OpenAsync(cancellationToken);

        await using NpgsqlCommand command = new(
            """
            SELECT column_name, data_type
            FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = @table
            """,
            connection);

        command.Parameters.AddWithValue("table", table);

        await using NpgsqlDataReader reader = await command.ExecuteReaderAsync(cancellationToken);

        while (await reader.ReadAsync(cancellationToken))
        {
            columns[reader.GetString(0)] = reader.GetString(1);
        }

        return columns;
    }

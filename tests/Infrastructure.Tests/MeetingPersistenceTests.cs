    [Theory]
    [InlineData("meetings", MeetingConfiguration.TitleAndDateIndexName, "title")]
    [InlineData("meeting_notes", MeetingConfiguration.NotesMeetingIndexName, "meeting_id")]
    public async Task The_AD20_unique_indexes_exist_by_name(string table, string index, string column)
    {
        CancellationToken cancellationToken = TestContext.Current.CancellationToken;
        string connectionString = await MigratedDatabaseAsync($"indexes_{table}", cancellationToken);

        await using NpgsqlConnection connection = new(connectionString);
        await connection.OpenAsync(cancellationToken);

        await using NpgsqlCommand command = new(
            """
            SELECT indexdef
            FROM pg_indexes
            WHERE schemaname = 'public' AND tablename = @table AND indexname = @name
            """,
            connection);

        command.Parameters.AddWithValue("table", table);
        command.Parameters.AddWithValue("name", index);

        string? definition = (string?)await command.ExecuteScalarAsync(cancellationToken);

        Assert.NotNull(definition);
        Assert.Contains("UNIQUE", definition, StringComparison.Ordinal);
        Assert.Contains(column, definition, StringComparison.Ordinal);
    }

    [Fact]
    public async Task A_meeting_and_its_notes_persist_as_inserts_only()
    {
        CancellationToken cancellationToken = TestContext.Current.CancellationToken;
        RecordingCommandInterceptor recorder = new();

        await using ServiceProvider services = await MigratedHostAsync(
            nameof(A_meeting_and_its_notes_persist_as_inserts_only),
            cancellationToken,
            collection => collection.ConfigureDbContext<AppDbContext>(options => options.AddInterceptors(recorder)));

        // Migrating is a wall of DDL. Only what the write itself sends is of interest.
        recorder.Clear();

        Meeting meeting = NewMeeting("Weekly sync");
        meeting.AttachNotes("Dana will send the draft by Friday.", Created);

        await using (AsyncServiceScope scope = services.CreateAsyncScope())
        {
            scope.ServiceProvider.GetRequiredService<IMeetingRepository>().Add(meeting);
            await scope.ServiceProvider.GetRequiredService<IUnitOfWork>().CommitAsync(cancellationToken);
        }

        string[] touching =
        [
            .. recorder.Commands.Where(command =>
                command.Contains("meetings", StringComparison.OrdinalIgnoreCase)
                || command.Contains("meeting_notes", StringComparison.OrdinalIgnoreCase)),
        ];

        Assert.NotEmpty(touching);
        Assert.Contains(touching, command => command.Contains("INSERT INTO", StringComparison.OrdinalIgnoreCase));
        Assert.DoesNotContain(touching, command => command.Contains("UPDATE ", StringComparison.OrdinalIgnoreCase));
    }

    [Fact]
    public async Task The_persisted_ids_are_the_uuidv7s_the_domain_constructors_made()
    {
        CancellationToken cancellationToken = TestContext.Current.CancellationToken;
        await using ServiceProvider services = await MigratedHostAsync(nameof(The_persisted_ids_are_the_uuidv7s_the_domain_constructors_made), cancellationToken);

        Meeting meeting = NewMeeting("Weekly sync");
        MeetingNotes notes = meeting.AttachNotes("Dana will send the draft by Friday.", Created);

        Guid meetingId = meeting.Id;
        Guid notesId = notes.Id;

        await SaveAsync(services, meeting, cancellationToken);

        Meeting stored = await ReadAsync(services, meetingId, cancellationToken);

        Assert.Equal(meetingId, stored.Id);
        Assert.True(stored.HasNotes);
        Assert.Equal(notesId, stored.Notes!.Id);
        Assert.Equal(meetingId, stored.Notes.MeetingId);

        // Version 7: the nibble the UUIDv7 layout puts in byte 6. EF generated nothing, or these
        // would be database-side values with a different version.
        Assert.Equal(7, (stored.Id.ToByteArray(bigEndian: true)[6] & 0xF0) >> 4);
        Assert.Equal(7, (stored.Notes.Id.ToByteArray(bigEndian: true)[6] & 0xF0) >> 4);
    }

    [Theory]
    [InlineData("  leading and trailing  ")]
    [InlineData("first line\r\nsecond line\r\n")]
    [InlineData("mixed\r\nline\nendings\r\n   ")]
    public async Task Notes_round_trip_byte_for_byte(string pasted)
    {
        CancellationToken cancellationToken = TestContext.Current.CancellationToken;
        // A content-derived suffix so each theory row gets its own database. It is a digest rather
        // than string.GetHashCode, which is salted per process: that gave every run a different
        // database name, and a negative hash put a hyphen in the identifier.
        string suffix = Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(pasted)))[..8];

        await using ServiceProvider services = await MigratedHostAsync(
            $"{nameof(Notes_round_trip_byte_for_byte)}_{suffix}",
            cancellationToken);

        Meeting meeting = NewMeeting("Weekly sync");
        meeting.AttachNotes(pasted, Created);

        await SaveAsync(services, meeting, cancellationToken);

        Meeting stored = await ReadAsync(services, meeting.Id, cancellationToken);

        Assert.Equal(pasted, stored.Notes!.Text);
        Assert.Equal(Encoding.UTF8.GetBytes(pasted), Encoding.UTF8.GetBytes(stored.Notes.Text));

        // And the hash that came back is still the hash of what came back, so a row that had been
        // altered in the database could not pass as intact.
        Assert.Equal(
            Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(stored.Notes.Text))),
            stored.Notes.Sha256);
    }


    [Fact]
    public async Task Two_writers_attaching_notes_to_the_same_meeting_end_in_one_conflict()
    {
        CancellationToken cancellationToken = TestContext.Current.CancellationToken;
        await using ServiceProvider services = await MigratedHostAsync(nameof(Two_writers_attaching_notes_to_the_same_meeting_end_in_one_conflict), cancellationToken);

        Meeting meeting = NewMeeting("Weekly sync");
        await SaveAsync(services, meeting, cancellationToken);

        // Both scopes read the Meeting before either wrote, so the aggregate's own rule says yes
        // to both. The unique index on meeting_notes(meeting_id) is the only thing left.
        await using AsyncServiceScope first = services.CreateAsyncScope();
        await using AsyncServiceScope second = services.CreateAsyncScope();

        Meeting forFirst = await LoadAsync(first, meeting.Id, cancellationToken);
        Meeting forSecond = await LoadAsync(second, meeting.Id, cancellationToken);

        Assert.False(forFirst.HasNotes);
        Assert.False(forSecond.HasNotes);

        forFirst.AttachNotes("The first paste.", Created);
        await first.ServiceProvider.GetRequiredService<IUnitOfWork>().CommitAsync(cancellationToken);

        forSecond.AttachNotes("The second paste.", Created);

        ConcurrencyConflictException conflict = await Assert.ThrowsAsync<ConcurrencyConflictException>(
            () => second.ServiceProvider.GetRequiredService<IUnitOfWork>().CommitAsync(cancellationToken));

        Assert.IsAssignableFrom<DbUpdateException>(conflict.InnerException);

        // And the first paste is what a read still returns.
        Assert.Equal("The first paste.", (await ReadAsync(services, meeting.Id, cancellationToken)).Notes!.Text);
    }

